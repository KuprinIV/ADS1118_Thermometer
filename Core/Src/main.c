/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC_Init();
  MX_I2C1_Init();
  MX_SPI1_Init();
  MX_TIM1_Init();
  MX_TIM14_Init();
  /* USER CODE BEGIN 2 */

  // power on delay
  HAL_Delay(100);

  // power on
  DEV_PowerCtrl(1);

  // start timers
  HAL_TIM_Base_Start(&htim1);		// ADC conversion trigger
  HAL_TIM_Base_Start_IT(&htim14);	// scanning

  // start ADC conversion
  HAL_ADC_Start_DMA(&hadc, (uint32_t*)vbat_raw_data, VBAT_BUF_LEN);

  // init OLED
  SSD1315_Init();
  WindowsInit();

  // init ADS1118 ADC and start first conversion
  ADS1118_Init();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
	  // check scan timer event
	  if(is_timer_updated)
	  {
		  is_timer_updated = 0;	// reset flag

		  // scan button
		  if(DEV_ScanBtn(&btn_state))
		  {
			  switch(btn_state)
			  {
				  case NotPressed:
				  default:
					  break;

				  case Pressed:
					  break;


				  case LongPressed:
					  // make power off
	//				  PowerOff();
					  break;
			  }
		  }

		  // get data from ADS1118
		  dev_state.thermocouple_temp = 150; // test stub. TODO: add data output from ADS1118

		  // update display
		  RefreshWindow();
	  }

	  // check ADC conversion complete event
	  if(is_adc_conv_cplt)
	  {
		  is_adc_conv_cplt = 0;	// reset flag

		  // average samples data
		  for(uint16_t i = 0; i < VBAT_BUF_LEN; i++)
		  {
			  dev_state.vbat_mv += vbat_raw_data[i];
		  }
		  // get battery voltage in mV
		  dev_state.vbat_mv = 2*dev_state.vbat_mv*3360/(VBAT_BUF_LEN*4096);

		  // check battery low
		  if(dev_state.vbat_mv < VBAT_LOW_MV)
		  {
			  // make power off
//			  PowerOff();
		  }
	  }
  }
  /* USER CODE END 3 */
}

